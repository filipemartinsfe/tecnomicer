/**
 * _mkicon.mjs — generates assets/logo-icon.svg
 *
 * The mark is four parallel slats seen in perspective. Each slat is a
 * parallelogram: its long edges run along `u`, its end caps along `v`, and the
 * two are NOT perpendicular — that shear is what makes them read as panels
 * receding rather than as rotated pills.
 *
 * Corners are rounded by cutting back along both adjacent edges and joining
 * with a quadratic through the corner, so the radius stays true on a sheared
 * shape (a rect with rx + skew gives stretched elliptical corners instead).
 *
 * Dev-only. Run: node tools/_mkicon.mjs
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");

const rad = (d) => (d * Math.PI) / 180;
const U = rad(16);   // long axis, descending to the right
const V = rad(74);   // end-cap axis — sheared off the perpendicular, which is
                     // what makes the slats read as panels receding in depth
const u = [Math.cos(U), Math.sin(U)];
const v = [Math.cos(V), Math.sin(V)];

const add = (p, d, k) => [p[0] + d[0] * k, p[1] + d[1] * k];
const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const len = (a) => Math.hypot(a[0], a[1]);
const norm = (a) => { const l = len(a); return [a[0] / l, a[1] / l]; };
const f = (n) => Math.round(n * 10) / 10;

/** rounded polygon path from ordered points */
function rounded(pts, r) {
  const n = pts.length;
  let d = "";
  for (let i = 0; i < n; i++) {
    const prev = pts[(i - 1 + n) % n];
    const cur = pts[i];
    const next = pts[(i + 1) % n];
    const inDir = norm(sub(cur, prev));
    const outDir = norm(sub(next, cur));
    // never cut back more than half of either edge
    const rr = Math.min(r, len(sub(cur, prev)) / 2, len(sub(next, cur)) / 2);
    const start = add(cur, inDir, -rr);
    const end = add(cur, outDir, rr);
    d += i === 0 ? `M${f(start[0])} ${f(start[1])}` : `L${f(start[0])} ${f(start[1])}`;
    d += `Q${f(cur[0])} ${f(cur[1])} ${f(end[0])} ${f(end[1])}`;
  }
  return d + "Z";
}

/** slat: origin corner, length along u, length along v, corner radius */
function slat(P, L, T, r) {
  const A = P;
  const B = add(A, u, L);
  const C = add(B, v, T);
  const D = add(A, v, T);
  return rounded([A, B, C, D], r);
}

// Perpendicular to the long axis, pointing up-right: the direction the stack
// recedes in.
const nrm = [Math.sin(U), -Math.cos(U)];
const shear = Math.sin(V - U);          // perpendicular thickness per unit of T

const GAP = 11;      // white space between slats
const STEP = 62;     // how far each slat slides along its own axis

// near → far. The near slat is short and deep; distance stretches the others
// out and flattens them, which is what sells the perspective.
const spec = [
  { L: 205, T: 215, r: 26, fill: "tmO" },
  { L: 252, T: 96,  r: 16, fill: "tmA" },
  { L: 244, T: 80,  r: 14, fill: "tmB" },
  { L: 234, T: 66,  r: 12, fill: "tmC" }
];

let cursor = [20, 250];
const slats = spec.map((s, i) => {
  const P = cursor;
  // P is the top corner and each slat hangs below it, so clearing the next
  // slat means rising by that slat's own perpendicular thickness plus the gap
  const next = spec[i + 1];
  const rise = GAP + (next ? next.T * shear : 0);
  cursor = add(add(P, nrm, rise), u, STEP);
  return { ...s, P };
});

// bounds
let minX = 1e9, minY = 1e9, maxX = -1e9, maxY = -1e9;
for (const s of slats) {
  for (const p of [s.P, add(s.P, u, s.L), add(add(s.P, u, s.L), v, s.T), add(s.P, v, s.T)]) {
    minX = Math.min(minX, p[0]); maxX = Math.max(maxX, p[0]);
    minY = Math.min(minY, p[1]); maxY = Math.max(maxY, p[1]);
  }
}
const pad = 6;
const vb = `${f(minX - pad)} ${f(minY - pad)} ${f(maxX - minX + pad * 2)} ${f(maxY - minY + pad * 2)}`;

const grad = (id, a, b, c, dd) => `    <linearGradient id="${id}" x1="0" y1="0" x2=".62" y2="1">
      <stop offset="0" stop-color="${a}"/>
      <stop offset=".43" stop-color="${b}"/>
      <stop offset=".47" stop-color="${c}"/>
      <stop offset="1" stop-color="${dd}"/>
    </linearGradient>`;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" role="img" aria-label="Tecnomicer">
  <title>Tecnomicer</title>
  <!-- Four slats in perspective; the near one carries the brand orange.
       Rebuilt as vector from the supplied raster lockup. Generated by
       tools/_mkicon.mjs — edit there, not here. If the original vector
       artwork (AI / EPS / SVG) turns up, replace this file with it. -->
  <defs>
${grad("tmO", "#F8AB60", "#F39038", "#EE7E13", "#E46E08")}
${grad("tmA", "#868A8E", "#4B4E51", "#2B2D30", "#17181A")}
${grad("tmB", "#9EA4A8", "#5D6165", "#36383B", "#1F2123")}
${grad("tmC", "#D0D4D7", "#8E9297", "#4F5256", "#2E3134")}
  </defs>
${[...slats].reverse().map((s) => `  <path fill="url(#${s.fill})" d="${slat(s.P, s.L, s.T, s.r)}"/>`).join("\n")}
</svg>
`;

await writeFile(join(repo, "assets/logo-icon.svg"), svg, "utf8");
console.log(`assets/logo-icon.svg  viewBox="${vb}"`);

/* ── favicon ──────────────────────────────────────────────────────────
   A white rounded tile so the graphite slats stay visible on a dark tab
   strip and the orange stays visible on a light one. */
const W = minX - pad, H = minY - pad;
const bw = maxX - minX + pad * 2, bh = maxY - minY + pad * 2;
const box = 64, inset = 5;
const s = (box - inset * 2) / bw;
const tx = inset - W * s;
const ty = (box - bh * s) / 2 - H * s;

const paths = [...slats].reverse()
  .map((sl) => `    <path fill="url(#${sl.fill})" d="${slat(sl.P, sl.L, sl.T, sl.r)}"/>`)
  .join("\n");

